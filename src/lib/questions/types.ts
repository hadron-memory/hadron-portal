/** portal#2234 — the shape of `QUESTION_CARD_FIELDS` (hadron-server#4427/#4428). */
export type QuestionPerson = { id: string; handle: string | null; name: string | null };
export type QuestionActor = { user: QuestionPerson | null; worker: QuestionPerson | null; app: QuestionPerson | null };
export type QuestionOption = { key: string; label: string; whyChoose: string | null; whyNot: string | null; risks: string | null };
export type QuestionRef = { ref: string | null; node: string | null; spec: string | null };
export type QuestionEntry = {
  kind: 'ANSWER' | 'RETRACTION' | string;
  key: string | null;
  text: string | null;
  reason: string | null;
  at: string;
  via: string | null;
  by: QuestionPerson | null;
};
export type QuestionState = 'OPEN' | 'DECIDED' | 'ANSWERED_UNCONFIRMED' | 'STALE' | 'WITHDRAWN' | 'TAMPERED' | 'UNVERIFIABLE';
export type QuestionCardData = {
  id: string;
  urn: string;
  portalUrl: string | null;
  code: string;
  title: string;
  background: string | null;
  whyNow: string | null;
  priority: string | null;
  tier: string | null;
  authorizes: boolean;
  state: QuestionState;
  answered: boolean;
  revSeq: number;
  viewerIsDecider: boolean;
  viewerMayAnswer: boolean;
  neededBy: string | null;
  defaultAction: string | null;
  askedAt: string | null;
  answeredAt: string | null;
  options: QuestionOption[];
  recommendation: { key: string; reason: string | null; by: QuestionActor | null } | null;
  noRecommendationReason: string | null;
  answer: QuestionEntry | null;
  answers: QuestionEntry[];
  blocks: QuestionRef[];
  sources: QuestionRef[];
  specsTouched: QuestionRef[];
  specsMustChange: QuestionRef[];
  deciders: QuestionPerson[];
  assignee: QuestionPerson | null;
  effectiveAssignee: QuestionPerson | null;
  askedBy: QuestionActor | null;
  withdrawn: { at: string; reason: string | null; by?: QuestionPerson | null } | null;
  /** Added by the loader, not the server: who is looking, and whether as someone else. */
  viewerId: string | null;
  impersonating: boolean;
};
